from pathlib import Path
from typing import Optional
import joblib
import numpy as np
from fastapi import FastAPI
from pydantic import BaseModel, Field

BASE = Path(__file__).resolve().parent
MODEL_DIR = BASE / "models"
MODEL_FILE = MODEL_DIR / "team_match_ensemble.joblib"
CLUSTER_FILE = MODEL_DIR / "student_profile_kmeans.joblib"

app = FastAPI(title="SmartTeam AI ML Service", version="1.0")
model = joblib.load(MODEL_FILE) if MODEL_FILE.exists() else None
kmeans = joblib.load(CLUSTER_FILE) if CLUSTER_FILE.exists() else None

class MatchFeatures(BaseModel):
    skill_match: float = Field(ge=0, le=100)
    interest_match: float = Field(ge=0, le=100)
    availability: float = Field(ge=0, le=100)
    experience: float = Field(ge=0, le=100)
    communication: float = Field(default=70, ge=0, le=100)
    reliability: float = Field(default=70, ge=0, le=100)

class ClusterFeatures(BaseModel):
    skill_match: float = Field(ge=0, le=100)
    interest_match: float = Field(ge=0, le=100)
    availability: float = Field(ge=0, le=100)
    experience: float = Field(ge=0, le=100)

@app.get("/")
def root():
    return {"service":"SmartTeam AI ML","status":"running","model_loaded":model is not None}

@app.get("/health")
def health():
    return {"status":"UP","model_loaded":model is not None,"cluster_model_loaded":kmeans is not None}

@app.post("/predict")
def predict(x: MatchFeatures):
    if model is None:
        raise RuntimeError("Model not found. Run train_models.py first.")
    arr = np.array([[x.skill_match,x.interest_match,x.availability,x.experience,x.communication,x.reliability]])
    probability = float(model.predict_proba(arr)[0][1])
    return {"label": "COMPATIBLE" if probability >= 0.5 else "LOW_COMPATIBILITY", "probability": round(probability,4)}

@app.post("/cluster")
def cluster(x: ClusterFeatures):
    if kmeans is None:
        raise RuntimeError("Cluster model not found. Run train_models.py first.")
    arr = np.array([[x.skill_match,x.interest_match,x.availability,x.experience]])
    label = int(kmeans.predict(arr)[0])
    return {"cluster": label, "meaning":"Student profile segment generated by K-Means"}
